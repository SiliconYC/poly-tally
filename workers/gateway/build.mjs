import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { checkGatewayPolicy } from "../../scripts/check-gateway-policy.mjs";
const root = resolve(import.meta.dirname, "../..");
await checkGatewayPolicy();
const result = await build({
  entryPoints: [resolve(import.meta.dirname, "src/index.mjs")],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  write: false,
  metafile: true,
  minify: false,
  legalComments: "inline",
  charset: "utf8",
  plugins: [
    {
      name: "original-validator-web-target",
      setup(build) {
        build.onResolve({ filter: /^node:crypto$/ }, () => ({
          path: resolve(import.meta.dirname, "src/crypto-shim.mjs"),
        }));
        build.onResolve({ filter: /^node:/ }, (args) => ({
          path: args.path,
          namespace: "unavailable-node",
        }));
        build.onLoad({ filter: /.*/, namespace: "unavailable-node" }, () => ({
          contents:
            'const unavailable=()=>{throw new Error("node_api_unavailable_in_worker")};export {unavailable as readFile,unavailable as writeFile,unavailable as rename,unavailable as rm,unavailable as mkdir,unavailable as readdir,unavailable as lstat,unavailable as resolve,unavailable as join,unavailable as pathToFileURL};',
        }));
        build.onLoad(
          { filter: /scripts\/(?:metrics|publish-snapshot)\.mjs$/ },
          async (args) => {
            const original = await readFile(args.path, "utf8");
            const marker = /\nif\s*\(process\.argv\[1\]/;
            if (!marker.test(original))
              throw new Error(
                "Original validator CLI boundary changed; review bundle adapter",
              );
            return {
              contents: original.slice(0, original.search(marker)),
              loader: "js",
              resolveDir: resolve(args.path, ".."),
            };
          },
        );
      },
    },
  ],
});
if (
  Object.values(result.metafile.outputs).some((output) => output.imports.length)
)
  throw new Error("Dashboard bundle must be self-contained");
const code =
  "// GENERATED: npm --prefix workers/gateway run build. Do not edit this file alone.\n// Only code/public configuration; NO credentials or runtime snapshots.\n// Existing Secrets: GITHUB_READ_TOKEN, GITHUB_PUBLISH_TOKEN, GATEWAY_KEY.\n// Real Cloudflare Free CPU/private access acceptance is still required.\n" +
  result.outputFiles[0].text;
if (
  code.includes("node_api_unavailable_in_worker") ||
  /from ["']node:/.test(code) ||
  code.includes("bootstrap_baseline_default")
)
  throw new Error("Forbidden runtime dependency/data in Dashboard bundle");
const output = resolve(root, "poly-tally-gateway-worker.js");
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== code)
    throw new Error("Committed Dashboard source is stale; rebuild");
} else await writeFile(output, code);
console.log(
  `Self-contained Dashboard Worker verified (${Buffer.byteLength(code)} bytes); no deployment performed.`,
);
