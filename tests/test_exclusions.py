    def test_Eigen目录全局排除且不误伤自有算法(self) -> None:
        for 路径 in (
            "Eigen/Core.h", "eigen/src/Core/Matrix.h", "EIGEN/README.md",
            "src/Eigen/src/Core/Matrix.h", "tests/fixtures/eIgEn/Matrix.cpp",
            "G_套件/二维点集加权直线拟合/Eigen/src/Cholesky/LLT.h",
        ):
            with self.subTest(路径=路径):
                self.assertIsNone(self.规则.api_语言(路径))
        for 路径 in ("src/eigen_solver.cpp", "src/EigenSolver/Matrix.cpp", "docs/eigen.md"):
            with self.subTest(路径=路径):
                self.assertIsNotNone(self.规则.api_语言(路径))

    def test_外部导航片段不因换目录而伪装成自写HTML(self) -> None:
        内容 = '<div class="sidebar-tree">\n' + '\n'.join(
            f'<li class="toctree-l1"><a class="reference internal" href="bpy.{序号}.html">API</a></li>'
            for 序号 in range(12)
        ) + '\n</div>\n'
        self.assertIsNone(行统计_类.api_解析(内容.encode(), "HTML"))

    def test_明确生成器标记与第三方分发头不进入代码量(self) -> None:
        样本 = [
            (b'<!doctype html>\n<meta name="generator" content="Sphinx 8.0">\n<div>API</div>\n', "HTML"),
            (b'/**\n * @license React\n * react.development.js\n * Copyright (c) Facebook, Inc. and its affiliates.\n */\nvar downloaded = 1;\n', "JavaScript"),
            (b'// Code generated by protoc-gen-go. DO NOT EDIT.\npackage example\n', "Go"),
            (b'# Generated by the protocol buffer compiler. DO NOT EDIT!\nx = 1\n', "Python"),
            (b'/* Generated by Cython 3.0.10 */\nint generated = 1;\n', "C"),
        ]
        for 内容, 语言 in 样本:
            with self.subTest(语言=语言):
                self.assertIsNone(行统计_类.api_解析(内容, 语言))

    def test_改成TXT或JSON后缀的重复运行日志仍排除(self) -> None:
        普通日志 = '\n'.join(f'2026-10-21 12:00:{序号:02d},123 - worker - INFO - tick {序号}' for 序号 in range(10))
        结构日志 = '\n'.join(json.dumps({"timestamp": f"2026-10-21T12:00:{序号:02d}Z", "level": "info", "message": "tick"}) for 序号 in range(10))
        self.assertIsNone(行统计_类.api_解析(普通日志.encode(), "Text"))
        self.assertIsNone(行统计_类.api_解析(结构日志.encode(), "JSON"))

    def test_日志实现文档示例与普通版权头不会被内容误判(self) -> None:
        样本 = [
            (b'# Copyright (c) 2026 Our Team\n# Do not edit production configuration directly.\nlogger.info("2026-10-21 INFO start")\n', "Python"),
            (b'// React UI implemented here\nexport const App = () => "hello";\n', "JavaScript"),
            (b'<div class="sidebar-tree"><a class="reference internal">My app</a></div>\n', "HTML"),
            (b'# Logging guide\n\n```text\n2026-10-21 12:00:00 INFO example\n```\nExplain the output here.\n', "Markdown"),
            (b'{"timestamp":"2026-10-21T12:00:00Z","level":"info","message":"fixture"}\n', "JSON"),
            (b'def render_header():\n    return """\n# Generated by the protocol buffer compiler. DO NOT EDIT!\n"""\n', "Python"),
            (b'def test_generated_header():\n    sample = """\n// Code generated by protoc. DO NOT EDIT.\n"""\n', "Python"),
        ]
        for 内容, 语言 in 样本:
            with self.subTest(语言=语言, 内容=内容):
                self.assertIsNotNone(行统计_类.api_解析(内容, 语言))

    def test_长篇日志教程保留且实际日志仍识别(self) -> None:
        日志 = '\n'.join(f'2026-10-21 12:00:{序号 % 60:02d} INFO tick' for 序号 in range(100))
        文档 = '# 日志解释\n\n```text\n' + 日志 + '\n```\n\n这里解释输出。\n'
        self.assertIsNotNone(行统计_类.api_解析(文档.encode(), "Markdown"))
        self.assertIsNone(行统计_类.api_解析(日志.encode(), "Text"))

    def test_机器三维资产数据不当作JSON程序代码(self) -> None:
        网格 = {
            "positions": [[0, 0, 0], [1, 0, 0], [0, 1, 0]], "triangles": [[0, 1, 2]],
            "weights": [[1], [1], [1]], "jointIndices": [[0], [0], [0]],
            "joints": [{"name": "root", "parent": -1, "position": [0, 0, 0]}],
        }
        采样 = {"time": 0, "feet": {"L": [0, 0, 0], "R": [0, 0, 0]}, "pelvis": [0, 0, 0], "root": [0, 0, 0], "contacts": {"L": True, "R": True}}
        烘焙 = {
            "librarySha256": "a" * 64, "bakeFps": 30, "coordinateSystem": "Y-up",
            "sourceLibrary": {"file": "motion.dat", "sha256": "a" * 64, "bytes": 100},
            "characters": {"example": {"file": "rig.json", "sha256": "b" * 64, "bytes": 100, "rootMotion": {}, "groundOffsets": {}}},
            "actions": {"idle": {"duration": 1, "loop": True, "description": "idle", "samples": [采样]}},
        }
        绑定 = {
            "boneCount": 1, "restLocal": [{"semantic": "root", "name": "root", "position": [0, 0, 0], "quaternion": [0, 0, 0, 1]}],
            "restPositions": {"root": [0, 0, 0]}, "referencePositions": {"root": [0, 0, 0]},
            "parents": {"root": None}, "map": {"root": "root"}, "rolls": {"root": [0, 0, 0, 1]},
        }
        for 内容 in (网格, 烘焙, 绑定):
            with self.subTest(键=list(内容)):
                self.assertIsNone(行统计_类.api_解析(json.dumps(内容).encode(), "JSON"))
        网格["positions"][0][0] = 10 ** 400
        self.assertIsNone(行统计_类.api_解析(json.dumps(网格).encode(), "JSON"))

